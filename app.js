function computeStreak(){
  const set = new Set(state.completedDates);
  let count = 0;
  let cur = new Date();
  // if today not done yet, streak still counts from yesterday backward
  if(!set.has(todayStr(cur))){
    cur.setDate(cur.getDate()-1);
  }
  while(set.has(todayStr(cur))){
    count++;
    cur.setDate(cur.getDate()-1);
  }
  return count;
}

